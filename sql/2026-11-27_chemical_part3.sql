-- Chemical part 3 (2026-11-27): new-chemical approval, exposure monitoring, major-hazard classes, spills.
CREATE TABLE IF NOT EXISTS chem_requests (
	id SERIAL NOT NULL, 
	company_id INTEGER NOT NULL, 
	substance_id INTEGER, 
	name VARCHAR(200) NOT NULL, 
	cas VARCHAR(40), 
	supplier VARCHAR(160), 
	purpose VARCHAR(1000) NOT NULL, 
	location VARCHAR(160) NOT NULL, 
	quantity FLOAT, 
	unit VARCHAR(12), 
	groups TEXT, 
	sds_date DATE, 
	alternative VARCHAR(1000), 
	controls VARCHAR(1000), 
	checks TEXT, 
	status VARCHAR(10) NOT NULL, 
	decision_note VARCHAR(1000), 
	decided_by INTEGER, 
	decided_at TIMESTAMP WITHOUT TIME ZONE, 
	item_id INTEGER, 
	requested_by INTEGER, 
	created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(company_id) REFERENCES companies (id) ON DELETE CASCADE, 
	FOREIGN KEY(substance_id) REFERENCES chem_substances (id) ON DELETE SET NULL, 
	FOREIGN KEY(decided_by) REFERENCES users (id) ON DELETE SET NULL, 
	FOREIGN KEY(item_id) REFERENCES chem_items (id) ON DELETE SET NULL, 
	FOREIGN KEY(requested_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_chem_requests_company_id ON chem_requests (company_id);
CREATE TABLE IF NOT EXISTS chem_exposures (
	id SERIAL NOT NULL, 
	company_id INTEGER NOT NULL, 
	user_id INTEGER, 
	person VARCHAR(120) NOT NULL, 
	seg VARCHAR(120) NOT NULL, 
	item_id INTEGER, 
	substance VARCHAR(200) NOT NULL, 
	cas VARCHAR(40), 
	kind VARCHAR(4) NOT NULL, 
	unit VARCHAR(6) NOT NULL, 
	periods TEXT NOT NULL, 
	value FLOAT NOT NULL, 
	"limit" FLOAT NOT NULL, 
	limit_source VARCHAR(200), 
	ratio FLOAT NOT NULL, 
	result VARCHAR(8) NOT NULL, 
	sampled_on DATE NOT NULL, 
	note VARCHAR(500), 
	created_by INTEGER, 
	created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(company_id) REFERENCES companies (id) ON DELETE CASCADE, 
	FOREIGN KEY(user_id) REFERENCES users (id) ON DELETE SET NULL, 
	FOREIGN KEY(item_id) REFERENCES chem_items (id) ON DELETE SET NULL, 
	FOREIGN KEY(created_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_chem_exposures_company_id ON chem_exposures (company_id);
CREATE TABLE IF NOT EXISTS chem_mh_classes (
	item_id INTEGER NOT NULL, 
	company_id INTEGER NOT NULL, 
	seveso_cats TEXT, 
	seveso_named VARCHAR(10), 
	psm_key VARCHAR(10), 
	conv_kg FLOAT, 
	set_by INTEGER, 
	set_at TIMESTAMP WITHOUT TIME ZONE NOT NULL, 
	PRIMARY KEY (item_id), 
	FOREIGN KEY(item_id) REFERENCES chem_items (id) ON DELETE CASCADE, 
	FOREIGN KEY(company_id) REFERENCES companies (id) ON DELETE CASCADE, 
	FOREIGN KEY(set_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_chem_mh_classes_company_id ON chem_mh_classes (company_id);
CREATE TABLE IF NOT EXISTS chem_spills (
	id SERIAL NOT NULL, 
	company_id INTEGER NOT NULL, 
	item_id INTEGER, 
	chemical VARCHAR(200) NOT NULL, 
	location VARCHAR(160), 
	size VARCHAR(6) NOT NULL, 
	amount VARCHAR(60), 
	description VARCHAR(1000), 
	injuries BOOLEAN NOT NULL, 
	reached_drain BOOLEAN NOT NULL, 
	status VARCHAR(6) NOT NULL, 
	close_note VARCHAR(1000), 
	reported_by INTEGER, 
	reported_at TIMESTAMP WITHOUT TIME ZONE NOT NULL, 
	closed_by INTEGER, 
	closed_at TIMESTAMP WITHOUT TIME ZONE, 
	PRIMARY KEY (id), 
	FOREIGN KEY(company_id) REFERENCES companies (id) ON DELETE CASCADE, 
	FOREIGN KEY(item_id) REFERENCES chem_items (id) ON DELETE SET NULL, 
	FOREIGN KEY(reported_by) REFERENCES users (id) ON DELETE SET NULL, 
	FOREIGN KEY(closed_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_chem_spills_company_id ON chem_spills (company_id);
